-- +goose Up
-- THE OPERATOR TIER, PER FAMILY MEMBER - the table the game's own permission
-- already has, in PostgreSQL.
--
-- WHY IT EXISTS. Every test tonight needed a developer flag and a restart
-- (`-spawndummy`, `-respawn`, `-splock`). The owner asked for the levers IN the
-- game instead: a chat line the zone can dispatch. A command surface with no
-- permission check is a remote admin panel on a server that verifies no password
-- (`barrack\handler.go:601-605`), so the check comes first.
--
-- THE REFERENCE IS `GE_DATA.dbo.ACCOUNT_LEVEL(MEMBER_ID, LEVEL)`, which exists in
-- our SQL Server container and holds zero rows. The shipped v32 ZoneServer reads
-- it per family member, and level 1 is the GM tier (offlinespada PROVEN v32;
-- see the comment on card t_67a2d4e3). This table mirrors it. `LEVEL_PERMISSION_IP`
-- from that project's notes does NOT exist in our schema and is deliberately not
-- ported.
--
-- THE KEY IS `MEMBER_ID`, the one column this table and `account_info` share. The
-- Go zone looks the row up once at CZ_START_GAME by the login id the client sent;
-- it does not join through `account_id`, because a GM grant follows the PERSON
-- (their login), not a numeric account row.
--
-- LEVEL 0 IS NOT A RULE ABOUT ANYONE; IT IS THE ABSENCE OF A GRANT. A member with
-- no row is level 0 (`GmLevelOf` answers 0 for ErrNoRows). The two seed rows below
-- exist so the table starts truthful against the three accounts this database
-- already holds.
--
-- THE `arcanine` SEED IS THE OPERATOR'S OWN ACCOUNT, NOT A RULE. It is set to 1 so
-- the owner can type a command and watch it work after this migration. It is not
-- a default for new accounts, and `test01` / `90000000000000001` are seeded at 0
-- to say so out loud. Move the grant with one UPDATE; do not edit this file.
--
-- IDEMPOTENT ON PURPOSE. Every statement is safe to run twice - goose normally
-- applies it once, but a hand-applied run (psql, for evidence) must not leave a
-- half-made table behind.

CREATE TABLE IF NOT EXISTS account_level (
    member_id varchar(20) PRIMARY KEY,   -- the login id, as account_info.member_id
    level     smallint    NOT NULL DEFAULT 0
);

COMMENT ON TABLE account_level IS
    'The family member''s operator tier. Level 1 = GM commands are dispatched; '
    'any other value, and an absent row, means level 0 (no commands). Read once '
    'per zone entry by goserver\zone, never per chat line.';

COMMENT ON COLUMN account_level.level IS
    '1 = the GM tier, as the shipped server reads ACCOUNT_LEVEL. There is no '
    'higher tier in this build; a command checks for exactly 1.';

-- The operator's account, and the two others at 0. `SELECT ... FROM account_info`
-- rather than three literals keeps this migration honest on a database whose
-- accounts have been renamed: it seeds every account that exists, granting only
-- the operator's login.
INSERT INTO account_level (member_id, level)
SELECT member_id, CASE WHEN member_id = 'arcanine' THEN 1 ELSE 0 END
  FROM account_info
ON CONFLICT (member_id) DO NOTHING;

