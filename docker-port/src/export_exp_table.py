"""export_exp_table.py - the two tables the Xp idspace gives, for the Go server.

ONE: the PC exp -> level curve (`barrack\\data\\exp_levels.csv`).
The barrack shows a character's level, and the level is NOT the database's LIFE
column: for 10 of the 12 characters here LIFE disagrees with the game's own
table (Grandies has LIFE 99 but is level 60; Hilda 104 but 140). The level, and
the cumulative total needed for the next level (`nextExp`), both come from EXP
through `ge_tables`.

TWO: the monster exp a kill pays (`zone\\data\\monster_exp.csv`) - added with R98
slice 2. `geMonsterLevelTable::GetExp(level)` reads the SAME idspace, a different
column: `source2\\geShared\\Source\\MonsterLevelTable.cpp:40-66` inserts every
row of the `Xp` idspace with ClassID <= 1000, keyed by that ClassID, and keeps
the column **MonXp** (`imcIES::GetClassList(Xp)` / `IMC_DECLARE_STRINGID(MonXp)`).
The file is the client's own `ge\\ies\\datatable_xp.ies` (the one `ge_tables`
already converts), so the numbers are the game's, not a guess.

Per the project rule, this is an ORACLE export: Python owns the table, Go must
not re-derive it. Both outputs are embedded in the Go binary and read at startup.

Usage (from src\\):
    python export_exp_table.py
"""
import os
import sys

import ge_paths
import ge_tables

OUT = os.path.join(ge_paths.ROOT, "goserver", "barrack", "data", "exp_levels.csv")
MAX_LEVEL = 300

MONSTER_OUT = os.path.join(ge_paths.ROOT, "goserver", "zone", "data",
                           "monster_exp.csv")
# CMonsterLevelTable::Init stops at the first row whose ClassID is over 1000
# (MonsterLevelTable.cpp:60-62), and GetExp finds by that ClassID.
MONSTER_MAX_CLASSID = 1000


def write_monster_exp():
    """level -> MonXp: what a kill pays BEFORE the monster's own EXP factor.

    The level is the row's ClassID, because that is the key `CMonsterLevelTable`
    inserts under and the key `GetExp(level)` looks up. A row with no MonXp is
    skipped, never written as 0 - a missing value must stay missing so the Go
    side can say "no row" instead of paying a number nobody printed.
    """
    table = []
    for c in ge_tables._convert("datatable_xp"):
        cid = int(c.get("ClassID"))
        if cid > MONSTER_MAX_CLASSID:
            continue
        raw = c.get("MonXp")
        if raw is None or raw == "":
            continue
        table.append((cid, int(float(raw))))
    if not table:
        print("the Xp idspace gave no MonXp rows")
        return 1
    table.sort()

    os.makedirs(os.path.dirname(MONSTER_OUT), exist_ok=True)
    with open(MONSTER_OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("# level,monster_exp - the Xp idspace, column MonXp\n")
        f.write("# geMonsterLevelTable::GetExp: rows ClassID <= 1000, keyed by ClassID\n")
        f.write("# (source2\\geShared\\Source\\MonsterLevelTable.cpp:40-66).\n")
        f.write("# Generated by src\\export_exp_table.py from ge\\ies\\datatable_xp.ies - do not edit.\n")
        for level, exp in table:
            f.write("%d,%d\n" % (level, exp))
    print("wrote %s (%d level(s), Lv %d = %d, Lv 100 = %d, Lv 130 = %d)"
          % (MONSTER_OUT, len(table), table[0][0], table[0][1],
             dict(table).get(100, 0), dict(table).get(130, 0)))
    return 0


def main():
    rows = []
    last = -1
    for level in range(1, MAX_LEVEL + 1):
        total = int(ge_tables.exp_of(level))
        if total <= last:
            # The table has stopped growing: past the last real level, so stop
            # instead of writing a flat run that would make the search ambiguous.
            break
        rows.append((level, total, int(ge_tables.promotion_band(level))))
        last = total

    if not rows:
        print("ge_tables.exp_of() returned nothing")
        return 1

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("# level,total_exp,promotion_band - exp cumulative, and the promotion cap\n")
        f.write("# Generated by src\\export_exp_table.py from ge_tables - do not edit.\n")
        for level, total, band in rows:
            f.write("%d,%d,%d\n" % (level, total, band))
    print("wrote %s (%d levels, up to exp %d)" % (OUT, len(rows), rows[-1][1]))

    # Sanity check against a real character, so a wrong table fails here.
    for name, exp in (("quick", rows[0][1]), ("mid", rows[len(rows) // 2][1])):
        lv = ge_tables.level_of(exp)
        print("  check: exp %d -> level %d (%s)" % (exp, lv, name))
    return write_monster_exp()


if __name__ == "__main__":
    sys.exit(main())
