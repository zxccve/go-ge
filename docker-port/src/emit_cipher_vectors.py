"""emit_cipher_vectors.py - prove the Go cipher interoperates, not just itself.

A round-trip test inside one implementation proves nothing about the client: it
only shows the code is its own inverse. The real question is "does the client
decrypt what Go encrypts?", and the honest proxy is "does Python's cipher, which
the client demonstrably accepts, produce the SAME bytes as Go for the same
plaintext?".

Blowfish-ECB is deterministic, so the answer must be identical bytes.

This writes `goserver\\protocol\\testdata\\cipher_vectors.txt`:
    <plain hex> <TAB> <wire hex> <TAB> <what it is>

Usage (from src\\):
    python emit_cipher_vectors.py
"""
import os
import struct
import sys

import ge_crypt
import ge_paths

OUT = os.path.join(ge_paths.ROOT, "goserver", "protocol", "testdata",
                   "cipher_vectors.txt")


def loginok(account_id, session_id, ident):
    """The working Python server's BC_LOGINOK: cmd(2) account(4) session(4) name."""
    b = struct.pack("<HII", 8, account_id, session_id) + ident.encode("latin-1")[:47]
    return b.ljust(57, b"\0")[:57]


def vectors():
    out = [("BC_LOGINOK 57 bytes", loginok(35, 0x3333, "Arcanine"))]
    # A short packet, to prove the 8-byte padding and the length word.
    out.append(("3-byte packet (padding case)", bytes([70, 0, 0])))
    # A large packet, to prove multi-block encryption and no 64 KB assumption.
    out.append(("8192-byte packet (many blocks)", bytes([16, 0]) + bytes(range(256)) * 32))
    return out


def main():
    lines = [
        "# Cipher interop vectors: plaintext -> the wire bytes Python produces.",
        "# Go must encrypt to the SAME bytes (Blowfish-ECB is deterministic).",
        "# Generated by src\\emit_cipher_vectors.py - regenerate, do not hand-edit.",
        "",
    ]
    for what, plain in vectors():
        wire = ge_crypt.encrypt_packet(plain)
        lines.append("%s\t%s\t%s" % (plain.hex(), wire.hex(), what))
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote %s (%d vectors)" % (OUT, len(lines) - 2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
