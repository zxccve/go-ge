"""emit_go_bf_tables.py - write the client's Blowfish init tables as Go source.

The cipher's tables are NOT the stock Blowfish pi digits: they are the client's
own scrambled `bf_dummy_table`, reassembled by `ge_crypt._reassemble`. Stock
Blowfish test vectors therefore do not apply, and the Go port cannot borrow a
stock table - it must use these exact numbers.

This script writes them out ONCE as `goserver\\protocol\\bfinit_tables.go`. The
key schedule itself is PORTED (see `crypt.go`), not baked in, so the port proves
the schedule as well as the round function. `protocol\\crypt_test.go` compares
the result against `testdata\\bf_keyschedule.txt`, which this script also writes.

Usage (from src\\):
    python emit_go_bf_tables.py
"""
import os
import sys

import ge_crypt
import ge_paths

GO_FILE = os.path.join(ge_paths.ROOT, "goserver", "protocol", "bfinit_tables.go")
KEY_FILE = os.path.join(ge_paths.ROOT, "goserver", "protocol", "testdata",
                        "bf_keyschedule.txt")

HEADER = """\
// Code generated by src\\emit_go_bf_tables.py - DO NOT EDIT.
//
// The client's Blowfish init tables. They are NOT the stock pi digits: they are
// the scrambled table in the client's own CryptTable.cpp. The key schedule in
// crypt.go expands these with the network key, so do not fold the key in here.
package protocol
"""


def word_rows(values, per_line=8):
    lines = []
    for i in range(0, len(values), per_line):
        row = ", ".join("0x%08x" % v for v in values[i:i + per_line])
        lines.append("\t" + row + ",")
    return lines


def write_go():
    P, S = ge_crypt.load_tables()
    out = [HEADER]
    out.append("// bfPInit is the P array before the key schedule (18 words).")
    out.append("var bfPInit = [18]uint32{")
    out += word_rows(P)
    out.append("}")
    out.append("")
    out.append("// bfSInit is the four S boxes before the key schedule (1024 words).")
    out.append("var bfSInit = [4][256]uint32{")
    for box in range(4):
        out.append("\t{ // S box %d" % box)
        out += word_rows(S[box])
        out.append("\t},")
    out.append("}")
    with open(GO_FILE, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("wrote %s" % GO_FILE)


def write_split_key():
    """The keyed tables ge_crypt uses at run time, as a check for the Go port."""
    KP, KS = ge_crypt._KP, ge_crypt._KS
    lines = [
        "# The keyed Blowfish tables ge_crypt uses at run time, for the Go port.",
        "# P (18 words), then four S boxes (256 words each), hex, one per line.",
        "# Generated by src\\emit_go_bf_tables.py - regenerate, do not hand-edit.",
        "# If the Go key schedule is right, it produces these exact numbers.",
        "",
    ]
    lines += ["P %d %08x" % (i, v) for i, v in enumerate(KP)]
    for box in range(4):
        lines += ["S%d %d %08x" % (box, i, v) for i, v in enumerate(KS[box])]
    os.makedirs(os.path.dirname(KEY_FILE), exist_ok=True)
    with open(KEY_FILE, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote %s (%d words)" % (KEY_FILE, len(KP) + sum(len(k) for k in KS)))


def main():
    write_go()
    write_split_key()
    return 0


if __name__ == "__main__":
    sys.exit(main())
