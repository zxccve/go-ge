"""export_commander_exp_table.py - write the COMMANDER level curve for Go.

`BC_COMMANDER_LV_INFO` (cmd 37) carries the family level, and that level is NOT
stored in any table: the real server sums an exp value from the CHARACTER LEVELS
and looks the total up in this curve (geCommLevelTable). The curve is the "Xp"
idspace rows with ClassID 1001..1999 - a different curve from the PC one, which
is why it must not be read with ge_tables.level_of().

Per the project rule this is an ORACLE export: Python owns the table, Go must
not re-derive it.

Usage (from src\\):
    python export_commander_exp_table.py
"""
import os
import sys

import ge_paths
import ge_tables

OUT = os.path.join(ge_paths.ROOT, "goserver", "barrack", "data",
                   "commander_exp_levels.csv")


def main():
    ge_tables._load()
    rows = list(ge_tables._COMMANDER)
    if not rows:
        print("the Xp idspace has no ClassID 1000..2000 rows")
        return 1

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("# level,total_exp - commander (family) level curve\n")
        f.write("# geCommLevelTable: the Xp idspace rows with 1000 < ClassID < 2000.\n")
        f.write("# Generated by src\\export_commander_exp_table.py - do not edit.\n")
        for level, total in rows:
            f.write("%d,%d\n" % (level, total))
    print("wrote %s (%d levels, %d..%d)" % (OUT, len(rows), rows[0][0], rows[-1][0]))

    # Sanity: the bands must be strictly increasing, or GetLevel's scan is
    # ambiguous and every answer after the flat point would be a guess.
    flat = [rows[i][0] for i in range(1, len(rows))
            if rows[i][1] <= rows[i - 1][1]]
    if flat:
        print("  WARNING: non-increasing TotalXp at levels %s" % flat[:10])
    return 0


if __name__ == "__main__":
    sys.exit(main())
